from __future__ import annotations

"""Reproducible non-rest control, deformation and socket transport court.

A canonical zero-control rest pass does not prove that its editable puppet can
actually move. Reuse the EXACT Mechanics solver to independently exercise each
declared control, deform CanonicalSkin and carry every declared joint/control
attachment socket into the changed pose. No joints, constraints, controls,
attachments, held props or source depth are generated by this court.

These are bounded *compiler intervention* witnesses, NOT source-observed
contact, learned secondary-motion, collision or deformation aesthetics proof.
"""

from dataclasses import asdict, dataclass, replace
import math
from typing import Any

import numpy as np

from .canonical_mesh_ir_v1 import CanonicalMeshIR
from .canonical_rig_ir_v2 import CanonicalRigIRV2
from .canonical_skin_ir_v2 import CanonicalSkinIRV2
from .canonical_mechanics_ir_v1 import CanonicalMechanicsIRV1
from .hashing import content_sha256
from .mechanics_control_solver_v1 import (
    ControlTransformIRV1,
    solve_control_pose_v1, deform_mesh_lbs_v1,
)
from .types import QualificationError
from .mechanics_attachment_socket_runtime_v1 import (
    solve_attachment_socket_world_v1 as _socket_poses,
)


@dataclass(frozen=True)
class MechanicsInterventionProbeV1:
    control_id: str
    mode: str
    input_translation_xyz: tuple[float, float, float]
    joint_motion_max: float
    vertex_motion_max: float | None
    full_mesh_deformation_tested: bool
    max_constraint_residual: float
    anchor_motion_max: float
    anchor_count: int
    pose_hash: str
    socket_pose_hash: str


@dataclass(frozen=True)
class MechanicsInterventionCourtV1:
    canonical_mesh_lineage_hash: str
    canonical_rig_lineage_hash: str
    canonical_skin_lineage_hash: str
    canonical_mechanics_lineage_hash: str
    baseline_socket_pose_hash: str
    probes: tuple[MechanicsInterventionProbeV1, ...]
    observed_joint_motion: bool
    observed_mesh_motion: bool
    control_count: int
    anchor_count: int
    full_mesh_deformation_probe_count: int
    full_mesh_deformation_complete: bool
    max_constraint_residual: float
    status: str
    court_hash: str
    schema: str = "RealSaS.MechanicsInterventionCourt.v1"
    source_attachment_contact_qualified: bool = False
    learned_secondary_motion_qualified: bool = False
    collision_qualified: bool = False
    source_pose_quality_qualified: bool = False
    edit_consequence_qualified: bool = False
    product_revision_minted: bool = False

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def compile_mechanics_intervention_court_v1(
    mesh: CanonicalMeshIR,
    rig: CanonicalRigIRV2,
    skin: CanonicalSkinIRV2,
    mechanics: CanonicalMechanicsIRV1,
    *,
    max_probed_controls: int = 128,
    max_full_mesh_deformation_probes: int = 4,
    relative_translation: float = 0.02,
    max_constraint_residual: float = 1e-3,
) -> MechanicsInterventionCourtV1:
    if (
        not isinstance(mesh, CanonicalMeshIR)
        or not isinstance(rig, CanonicalRigIRV2)
        or not isinstance(skin, CanonicalSkinIRV2)
        or not isinstance(mechanics, CanonicalMechanicsIRV1)
        or mechanics.mesh_lineage_hash != mesh.mesh_lineage_hash
        or mechanics.rig_lineage_hash != rig.rig_lineage_hash
        or mechanics.skin_lineage_hash != skin.skin_lineage_hash
        or rig.mesh_lineage_hash != mesh.mesh_lineage_hash
        or skin.deform_structure_hash != rig.deform_structure_hash
    ):
        raise QualificationError("INTERVENTION_CANONICAL_PARENT_LINEAGE_DRIFT")
    if (
        type(max_probed_controls) is not int
        or not 1 <= max_probed_controls <= 512
        or type(max_full_mesh_deformation_probes) is not int
        or not 1 <= max_full_mesh_deformation_probes <= 8
        or not rig.controls
        or len(rig.controls) > max_probed_controls
        or type(relative_translation) not in (float, int)
        or not math.isfinite(relative_translation)
        or not 0 < relative_translation <= 0.1
        or type(max_constraint_residual) not in (float, int)
        or not math.isfinite(max_constraint_residual)
        or max_constraint_residual < 0
    ):
        raise QualificationError("INTERVENTION_PROBE_POLICY_OR_BUDGET_INVALID")
    # Use the exact canonical scale, not a fixed humanoid-sized translation.
    rest = np.asarray([vertex.P for vertex in mesh.vertices], dtype=np.float64)
    if rest.ndim != 2 or rest.shape[1] != 3 or not np.isfinite(rest).all():
        raise QualificationError("INTERVENTION_MESH_REST_INVALID")
    scale = float(np.max(np.ptp(rest, axis=0)))
    if not math.isfinite(scale) or scale <= 1e-8:
        raise QualificationError("INTERVENTION_MESH_SCALE_DEGENERATE")
    shift = tuple(float(v) for v in (
        scale * relative_translation, scale * relative_translation * .4, 0.
    ))
    baseline_pose = solve_control_pose_v1(rig, ())
    baseline = deform_mesh_lbs_v1(mesh, rig, skin, baseline_pose)
    baseline_vertices = np.asarray(baseline.positions, dtype=np.float64)
    if not np.isfinite(baseline_vertices).all():
        raise QualificationError("INTERVENTION_REST_DEFORMATION_NONFINITE")
    baseline_socket = _socket_poses(rig, baseline_pose, ())
    baseline_joint = {row.canonical_joint_id: np.asarray(row.solved_P, dtype=np.float64)
                      for row in baseline_pose.joints}
    baseline_socket_hash = content_sha256(baseline_socket)
    probes = []
    maximum_residual = 0.0
    any_joint_motion, any_mesh_motion = False, False
    for index, control in enumerate(rig.controls):
        state = (ControlTransformIRV1(control.canonical_control_id, translation=shift),)
        pose = solve_control_pose_v1(rig, state)
        if (
            pose.rig_lineage_hash != rig.rig_lineage_hash
            or pose.control_program_hash != rig.control_program_hash
        ):
            raise QualificationError("INTERVENTION_POSED_PARENT_OR_VERTEX_ORDER_DRIFT")
        # Full Python LBS is O(vertex_count * influence_count). Testing all
        # controls on a 250k-vertex subject would exceed worker budgets.
        # The solver and socket transport cover EVERY control, while a fixed,
        # disclosed prefix gets full vertex-level deformation replay. This
        # court never claims all-control deformation coverage from samples.
        tested = index < max_full_mesh_deformation_probes
        xyz = None
        if tested:
            deformed = deform_mesh_lbs_v1(mesh, rig, skin, pose)
            if (
                deformed.canonical_mesh_vertex_ids != baseline.canonical_mesh_vertex_ids
                or deformed.mesh_lineage_hash != mesh.mesh_lineage_hash
                or deformed.skin_lineage_hash != skin.skin_lineage_hash
            ):
                raise QualificationError("INTERVENTION_DEFORMATION_PARENT_OR_VERTEX_ORDER_DRIFT")
            xyz = np.asarray(deformed.positions, dtype=np.float64)
            if xyz.shape != rest.shape or not np.isfinite(xyz).all():
                raise QualificationError("INTERVENTION_DEFORMATION_NONFINITE")
        joint_poses = {row.canonical_joint_id: np.asarray(row.solved_P, dtype=np.float64)
                       for row in pose.joints}
        if set(joint_poses) != set(baseline_joint):
            raise QualificationError("INTERVENTION_JOINT_IDENTITY_DRIFT")
        jm = max(float(np.linalg.norm(joint_poses[jid] - p))
                 for jid, p in baseline_joint.items())
        vm = (float(np.max(np.linalg.norm(xyz - baseline_vertices, axis=1)))
              if xyz is not None else None)
        if not math.isfinite(jm) or (vm is not None and not math.isfinite(vm)):
            raise QualificationError("INTERVENTION_DISPLACEMENT_NONFINITE")
        residual = max((float(v) for _, v in pose.constraint_residuals), default=0.)
        if not math.isfinite(residual) or residual > max_constraint_residual:
            raise QualificationError("INTERVENTION_CONSTRAINT_RESIDUAL_EXCEEDS_POLICY")
        sockets = _socket_poses(rig, pose, state)
        if set(sockets) != set(baseline_socket):
            raise QualificationError("INTERVENTION_SOCKET_IDENTITY_DRIFT")
        am = max((math.dist(sockets[name], baseline_socket[name])
                  for name in sockets), default=0.)
        if not math.isfinite(am):
            raise QualificationError("INTERVENTION_SOCKET_DISPLACEMENT_NONFINITE")
        probes.append(MechanicsInterventionProbeV1(
            control_id=control.canonical_control_id, mode="TRANSLATE_CANONICAL_CONTROL",
            input_translation_xyz=shift, joint_motion_max=jm, vertex_motion_max=vm,
            full_mesh_deformation_tested=tested,
            max_constraint_residual=residual, anchor_motion_max=am,
            anchor_count=len(sockets), pose_hash=content_sha256(pose.to_dict()),
            socket_pose_hash=content_sha256(sockets),
        ))
        maximum_residual = max(maximum_residual, residual)
        any_joint_motion |= jm > 1e-9
        any_mesh_motion |= vm is not None and vm > 1e-9
    receipt = MechanicsInterventionCourtV1(
        canonical_mesh_lineage_hash=mesh.mesh_lineage_hash,
        canonical_rig_lineage_hash=rig.rig_lineage_hash,
        canonical_skin_lineage_hash=skin.skin_lineage_hash,
        canonical_mechanics_lineage_hash=mechanics.mechanics_lineage_hash,
        baseline_socket_pose_hash=baseline_socket_hash, probes=tuple(probes),
        observed_joint_motion=any_joint_motion, observed_mesh_motion=any_mesh_motion,
        control_count=len(rig.controls), anchor_count=len(rig.attachment_anchors),
        full_mesh_deformation_probe_count=min(len(rig.controls), max_full_mesh_deformation_probes),
        full_mesh_deformation_complete=(len(rig.controls) <= max_full_mesh_deformation_probes),
        max_constraint_residual=maximum_residual,
        status="MEASURED_COMPILER_CONTROL_INTERVENTIONS_NOT_SOURCE_BEHAVIOR",
        court_hash="",
    )
    return replace(receipt, court_hash=content_sha256({
        k: v for k, v in receipt.to_dict().items() if k != "court_hash"
    }))


__all__ = [
    "MechanicsInterventionProbeV1", "MechanicsInterventionCourtV1",
    "compile_mechanics_intervention_court_v1",
]
