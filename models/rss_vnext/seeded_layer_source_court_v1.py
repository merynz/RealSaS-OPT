from __future__ import annotations

"""Native layer truth versus predicted layer hypothesis, never XYZ-only.

The ID namespace is an independently qualified source-native role partition,
not the student mesh's component ID. Student layers are generated by one H(x)
and compiler-sealed; native layers come from source face/material annotation.
Matching by identical XYZ across body/cape is forbidden even at exactly zero
distance. Non-layered product v1 remains a separately admitted source stage.
"""
from dataclasses import dataclass
from hashlib import sha256
from typing import Callable, Mapping

import torch
from torch import Tensor

from .animation_ready_mesh import RSSvNextStructuralMeshCandidate

SOURCE_LAYER_AUTHORITY = "QUALIFIED_SOURCE_NATIVE_FACE_TO_SEMANTIC_LAYER_V1"
SOURCE_LAYER_DERIVATION = "SOURCE_NATIVE_FACE_OR_MATERIAL_NO_STUDENT_PSEUDOLABEL"


@dataclass(frozen=True)
class LayerCorrespondenceV1:
    student_layer_ids: Tensor        # [V*] predicted from IRIS (not teacher!)
    source_layer_ids: Tensor         # [M] independent native-source evidence
    layer_count: int
    namespace_sha256: str

    def validate(self) -> None:
        a,b=self.student_layer_ids,self.source_layer_ids
        if (
            type(self.layer_count) is not int
            or not 2<=self.layer_count<=16
            or a.ndim!=1 or b.ndim!=1 or not len(a) or not len(b)
            or a.dtype!=torch.long or b.dtype!=torch.long
            or a.device!=b.device
            or bool((a<0).any()) or bool((b<0).any())
            or int(a.max())>=self.layer_count
            or int(b.max())>=self.layer_count
            or torch.unique(a).numel()!=self.layer_count
            or torch.unique(b).numel()!=self.layer_count
            or type(self.namespace_sha256) is not str
            or len(self.namespace_sha256)!=64
            or any(c not in "0123456789abcdef"
                   for c in self.namespace_sha256)
        ):
            raise ValueError("RSS_VNEXT_SEEDED_LAYER_SOURCE_DOMAIN")

    def grouped(self, student_indices: Tensor,
                source_indices: Tensor) -> tuple[tuple[Tensor,Tensor],...]:
        self.validate()
        if (
            student_indices.ndim!=1 or source_indices.ndim!=1
            or student_indices.dtype!=torch.long
            or source_indices.dtype!=torch.long
            or not len(student_indices) or not len(source_indices)
            or student_indices.device!=self.student_layer_ids.device
            or source_indices.device!=self.source_layer_ids.device
            or bool((student_indices<0).any())
            or bool((source_indices<0).any())
            or int(student_indices.max())>=len(self.student_layer_ids)
            or int(source_indices.max())>=len(self.source_layer_ids)
        ):
            raise ValueError("RSS_VNEXT_SEEDED_LAYER_SAMPLE_ADDRESS")
        output=[]
        for layer in range(self.layer_count):
            si=student_indices[
                self.student_layer_ids[student_indices]==layer
            ]
            ti=source_indices[
                self.source_layer_ids[source_indices]==layer
            ]
            if not si.numel() or not ti.numel():
                raise ValueError("RSS_VNEXT_SEEDED_LAYER_SOURCE_COVERAGE_ABSTAIN")
            output.append((si,ti))
        return tuple(output)


def qualify_layer_source_court_v1(
    mesh: RSSvNextStructuralMeshCandidate,
    *,
    source_layer_ids: Tensor | None,
    source_xyz: Tensor,
    receipt: Mapping[str,object],
    source_asset_sha256: str,
    tensor_digest: Callable[[Tensor],str],
    source_component_ids: Tensor | None = None,
) -> LayerCorrespondenceV1 | None:
    if mesh.seeded_surface is None:
        raise ValueError("RSS_VNEXT_SEEDED_LAYER_MESH_REQUIRED")
    seed=mesh.seeded_surface
    student=seed.vertex_layer_ids
    if student is None:
        if source_layer_ids is not None or any(k in receipt for k in (
            "source_layer_partition_authority",
            "source_layer_namespace_sha256",
            "native_source_layer_partition_sha256",
        )):
            raise ValueError("RSS_VNEXT_SEEDED_LAYER_UNLAYERED_TRUTH_FORBIDDEN")
        return None
    if (
        source_layer_ids is None
        or source_layer_ids.shape!=(source_xyz.shape[0],)
        or source_layer_ids.device!=source_xyz.device
        or source_layer_ids.dtype!=torch.long
        or source_component_ids is None
        or source_component_ids.shape!=source_layer_ids.shape
        or source_component_ids.device!=source_layer_ids.device
        or source_component_ids.dtype!=torch.long
        or receipt.get("source_layer_partition_authority")
            != SOURCE_LAYER_AUTHORITY
        or receipt.get("source_layer_partition_derivation")
            != SOURCE_LAYER_DERIVATION
        or receipt.get("source_layer_namespace_sha256")
            != seed.layer_namespace_sha256
        or receipt.get("source_layer_native_asset_sha256")
            != source_asset_sha256
        or receipt.get("native_source_layer_partition_sha256")
            != tensor_digest(source_layer_ids)
        or receipt.get("source_layer_independently_audited") is not True
        or receipt.get("source_label_student_checkpoint_dependency") is not False
    ):
        raise ValueError("RSS_VNEXT_SEEDED_LAYER_SOURCE_RECEIPT_REQUIRED")
    if (
        student.shape != (mesh.rest_vertices_iris.shape[1],)
        or seed.layer_namespace_sha256=="" or not seed.layer_names
        or not torch.equal(
            student[mesh.faces],
            student[mesh.faces[:,0:1]].expand(-1,3),
        )
    ):
        raise ValueError("RSS_VNEXT_SEEDED_LAYER_STUDENT_TOPOLOGY_DRIFT")
    # Source component IDs are native face-connected components, not student
    # components. Components cannot contain mixed layer truth.
    unique, inverse=torch.unique(
        source_component_ids,sorted=True,return_inverse=True,
    )
    lo=torch.full((len(unique),),2**31-1,
                  device=source_xyz.device,dtype=torch.long)
    hi=torch.full((len(unique),),-1,
                  device=source_xyz.device,dtype=torch.long)
    lo.scatter_reduce_(0,inverse,source_layer_ids,reduce="amin",include_self=True)
    hi.scatter_reduce_(0,inverse,source_layer_ids,reduce="amax",include_self=True)
    if not torch.equal(lo,hi):
        raise ValueError("RSS_VNEXT_SEEDED_LAYER_NATIVE_COMPONENT_CROSS_ROLE")
    court=LayerCorrespondenceV1(
        student_layer_ids=student,
        source_layer_ids=source_layer_ids,
        layer_count=len(seed.layer_names),
        namespace_sha256=seed.layer_namespace_sha256,
    )
    court.validate()
    return court


__all__=[
    "SOURCE_LAYER_AUTHORITY","SOURCE_LAYER_DERIVATION",
    "LayerCorrespondenceV1","qualify_layer_source_court_v1",
]
