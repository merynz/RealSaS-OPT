-- A research campaign coordinates multiple real subject Attempts without adding
-- a second scientific DAG. Every member remains an ordinary subject-bound
-- Attempt on the same sealed EngineRelease and target stage.
CREATE TABLE research_campaigns (
    id uuid PRIMARY KEY,
    name varchar(300) NOT NULL,
    baseline_engine_release_id uuid NOT NULL REFERENCES engine_releases(id) ON DELETE RESTRICT,
    candidate_engine_release_id uuid NOT NULL REFERENCES engine_releases(id) ON DELETE RESTRICT,
    target_stage_id varchar(100) NOT NULL,
    canonical_code_sha char(40) NOT NULL,
    spec_sha256 char(64) NOT NULL UNIQUE,
    state varchar(40) NOT NULL CHECK (state IN ('STARTING','READY','RUNNING','START_FAILED','SUBMIT_FAILED')),
    created_by varchar(300) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE research_campaign_members (
    campaign_id uuid NOT NULL REFERENCES research_campaigns(id) ON DELETE RESTRICT,
    subject_id uuid NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
    attempt_id uuid NOT NULL UNIQUE REFERENCES attempts(id) ON DELETE RESTRICT,
    member_role varchar(20) NOT NULL CHECK (member_role IN ('COHORT','REGRESSION')),
    ordinal integer NOT NULL CHECK (ordinal >= 0),
    PRIMARY KEY (campaign_id, subject_id),
    CONSTRAINT uq_research_campaign_role_ordinal UNIQUE (campaign_id, member_role, ordinal)
);
CREATE INDEX ix_research_campaign_members_subject ON research_campaign_members(subject_id, campaign_id);

CREATE TABLE research_campaign_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id uuid NOT NULL REFERENCES research_campaigns(id) ON DELETE RESTRICT,
    event_type varchar(100) NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_research_campaign_events_campaign_created
    ON research_campaign_events(campaign_id, created_at, id);

