@pytest.fixture(autouse=True)
def deterministic_cpu():
    torch.manual_seed(195)
    torch.set_num_threads(1)


def _real_surface_fixture():
    model = _network()
    rgba, camera = _images()
    cfg = model.cfg
    # The strict TESSA grammar is tested with a known-valid synthetic token
    # stream; inference geometry is still from the real shared H(x) and all
    # specialist heads on the single RSS unified model.
    source_vertices = np.asarray([
        [-.25, -.25, 0.0], [.25, -.25, 0.0], [-.25, .25, 0.0],
    ], dtype=np.float64)
    tokens = encode_adjacent_teacher_mesh_v1(
        source_vertices,
        np.asarray([[0, 1, 2]], dtype=np.int64),
        component_id="SYNTHETIC_TEST_ONLY", chart_id="SYNTHETIC_TEST_ONLY",
        cfg=TESSAConfigV1(coordinate_bins=cfg.tessa.coordinate_bins),
    ).token_ids
    with torch.no_grad():
        state, _, _ = model.encode_observations(rgba, camera)
        mesh = model.build_mesh_candidate(
            state, tuple(tokens),
            source_authority="LEARNED_PREDICTED_TOPOLOGY",
        )
    prediction = {
        "state": state,
        "mesh_candidate": mesh,
        "mesh_status": "UNQUALIFIED_MESH_CANDIDATE",
        "mesh_failure": None,
        "observed_view_count": 2,
        "auxiliary_view_authority": "LEARNED_PREDICTED_ONLY",
        "qualification_status": "UNQUALIFIED_NEURAL_PROPOSAL",
    }
    evidence = export_inference_evidence_v1(
        prediction, original_rgba=rgba,
        original_camera_features=camera, checkpoint_sha256="a" * 64,
    )
    carrier = encode_neural_scene_carrier_v1(state, evidence=evidence)
    return cfg, state, rgba, camera, evidence, carrier


def _fanout(cfg, evidence, carrier):
    return open_rss_vnext_expert_fanout_v1(
        evidence, carrier, model_config=cfg,
        expected_checkpoint_sha256="a" * 64,
        expected_model_config_sha256=architecture_digest(cfg),
    )


def test_compiler_replays_real_rss_mesh_and_preserves_all_specialist_face_fields():
    cfg, state, rgba, camera, evidence, carrier = _real_surface_fixture()
    reader = _fanout(cfg, evidence, carrier)
    before = reader.query(0)
    result = compile_rss_vnext_surface_candidates_v1(reader)
    assert result.state == "UNQUALIFIED_COMPUTED_SURFACE_CANDIDATE"
    assert result.source_inference_evidence_hash == evidence.evidence_hash
    assert result.neural_scene_carrier_sha256 == reader.neural_carrier_sha256
    assert result.unified_model_config_sha256 == architecture_digest(cfg)
    assert result.candidate_mesh_sha256
    assert result.topology_token_sequence_sha256
    assert len(result.faces) == len(evidence.mesh["faces"]) == 1
    assert not any((
        result.canonical_mesh_authority, result.signed_solid_authority,
        result.source_visibility_authority, result.independent_editability_authority,
    ))
    face = result.faces[0]
    assert face.candidate_face_index == 0
    assert face.candidate_vertex_indices == tuple(evidence.mesh["faces"][0])
    assert face.candidate_component_index == evidence.mesh["face_components"][0]
    assert face.area > 0
    assert np.linalg.norm(face.unit_normal_xyz) == pytest.approx(1., abs=1e-5)
    assert len(face.region_probabilities) == cfg.region_slots + 1
    assert sum(face.region_probabilities) == pytest.approx(1., abs=1e-6)
    assert face.region_probabilities[-1] > 0  # UNKNOWN stays UNKNOWN
    assert len(face.presentation_role_probabilities) == len(cfg.semantic_role_names)
    assert sum(face.presentation_role_probabilities) == pytest.approx(1., abs=1e-6)
    assert len(face.graphics_logits_by_corner) == 3
    for corner, vertex_index in enumerate(face.candidate_vertex_indices):
        assert face.graphics_logits_by_corner[corner] == tuple(
            evidence.mesh["graphics_logits"][vertex_index]
        )
        assert face.affordance_logits_by_corner[corner] == tuple(
            evidence.mesh["affordance_logits"][vertex_index]
        )
        assert face.original_rgba_by_corner[corner] == tuple(
            tuple(evidence.mesh["source_rays"]["rgba"][vertex_index][view])
            for view in range(2)
        )
        assert face.original_projection_valid_by_corner[corner] == tuple(
            evidence.mesh["source_rays"]["valid"][vertex_index]
        )
    assert not face.source_visibility_qualified
    assert not face.independent_drawable_qualified
    assert not face.mechanical_anchor_qualified
    # Canonicalization is NONDESTRUCTIVE: independently read the same H(x),
    # presentation roles, Graphics and directed mechanical slot relations.
    assert reader.query(0) == before
    assert reader.region_relation(0, 1).attachment_anchor_xyz is None


@pytest.mark.parametrize("corruption,code", [
    ("face_winding", "TESSA_TOKEN_MESH_DECODE_MISMATCH"),
    ("base_coordinate", "TESSA_TOKEN_MESH_DECODE_MISMATCH"),
    ("refined_normal", "NEURAL_NORMALS_NOT_FROM_INDEXED_GEOMETRY"),
])
def test_compiler_refuses_rehashed_mesh_not_equal_to_neural_token_geometry(
    corruption, code,
):
    cfg, state, _, _, evidence, carrier = _real_surface_fixture()
    mesh = deepcopy(evidence.mesh)
    if corruption == "face_winding":
        mesh["faces"][0][0], mesh["faces"][0][1] = (
            mesh["faces"][0][1], mesh["faces"][0][0],
        )
    elif corruption == "base_coordinate":
        mesh["base_xyz"][0][0] += .15
    elif corruption == "refined_normal":
        mesh["normals_xyz"][0][2] *= -1
    forged = seal_inference_evidence_v1(
        replace(evidence, mesh=mesh, evidence_hash=""),
    )
    # Carrier is pinned to the ORIGINAL evidence hash; forging a rehashed
    # mesh cannot silently rebind the scene to that altered geometry.
    with pytest.raises(RuntimeError, match="BINDING_OR_FIELDS_DRIFT"):
        _fanout(cfg, forged, carrier)
    # To exercise the *independent* TESSA geometry court, rebind the same
    # unchanged shared H(x) state under the forged candidate evidence.
    rebound = encode_neural_scene_carrier_v1(state, evidence=forged)
    reader = _fanout(cfg, forged, rebound)
    with pytest.raises(QualificationError, match=code):
        compile_rss_vnext_surface_candidates_v1(reader)


def test_compiler_keeps_all_rss_experts_when_topology_abstains():
    cfg, state, rgba, camera, _, _ = _real_surface_fixture()
    prediction = {
        "state": state,
        "mesh_candidate": None,
        "mesh_status": "ABSTAIN",
        "mesh_failure": "SYNTHETIC_UNTRAINED_TOPOLOGY_ABSTAIN",
        "observed_view_count": 2,
        "auxiliary_view_authority": "LEARNED_PREDICTED_ONLY",
        "qualification_status": "UNQUALIFIED_NEURAL_PROPOSAL",
    }
    evidence = export_inference_evidence_v1(
        prediction, original_rgba=rgba,
        original_camera_features=camera, checkpoint_sha256="a" * 64,
    )
    carrier = encode_neural_scene_carrier_v1(state, evidence=evidence)
    reader = _fanout(cfg, evidence, carrier)
    decision = compile_rss_vnext_surface_candidates_v1(reader)
    assert decision.state == "ABSTAIN_NO_VALID_TOPOLOGY"
    assert decision.faces == ()
    assert decision.candidate_mesh_sha256 is None
    assert decision.topology_token_sequence_sha256 is None
    assert decision.neural_scene_carrier_sha256 == reader.neural_carrier_sha256
    assert reader.query(0).region_membership_probabilities[-1] > 0
    assert reader.query(0).graphics_field_logits
    assert reader.region_relation(0, 1).attachment_anchor_xyz is None
    assert reader.availability.canonical_rig_skin == "NOT_QUALIFIED"
