from __future__ import annotations

"""BUSTED main-owned static UI + strict product-gateway contract court.

Preserves existing Awaken, Studio, Motion and Export art/source; no model,
proof or compile result is generated by this static site.
"""

from pathlib import Path
import json
import re
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "product" / "busted_site"
PAGES = ("index.html", "studio.html", "motion.html", "export.html")


def test_main_is_single_source_of_static_product_site():
    assert SITE.is_dir()
    files = sorted(p for p in SITE.rglob("*") if p.is_file())
    # Exact source tree migration from the live preview included all four
    # product pages, their editor scripts and VFX assets; not an empty shell.
    assert len(files) >= 90, (len(files), SITE)
    assert all((SITE / page).is_file() for page in PAGES)
    assert (SITE / "static/js/awaken.js").is_file()
    assert (SITE / "static/js/studio_weight_painter.js").is_file()
    assert (SITE / "static/js/studio_presentation_editor.js").is_file()
    assert (SITE / "static/js/studio_timeline.js").is_file()


def test_html_assets_exist_and_product_gateway_precedes_app_modules():
    for page in PAGES:
        html = (SITE / page).read_text(encoding="utf-8")
        bridge = './static/js/rss_vnext_api_gateway_v1.js'
        assert html.count(bridge) == 1, page
        assert html.index(bridge) < html.index("</head>"), page
        for target in re.findall(r'(?:src|href)\s*=\s*["\']([^"\']+)["\']', html):
            if target.startswith(("#", "data:", "https:", "http:", "mailto:", "/", "blob:")):
                continue
            path = urlsplit(target).path
            if not path:
                continue
            assert (SITE / path).is_file(), (page, target)


def test_js_imports_have_single_static_owner():
    imports = re.compile(r"""(?:from\s+|import\s*\()\s*['"]([.]/[^'"]+)['"]""")
    for file in (SITE / "static/js").rglob("*.js"):
        for ref in imports.findall(file.read_text(encoding="utf-8")):
            assert (file.parent / ref).is_file(), (file, ref)


def test_github_pages_has_no_false_product_release_claim():
    config = json.loads((SITE / "site-config.json").read_text(encoding="utf-8"))
    assert config == {
        "schema": "RealSaS.BUSTED.SiteGatewayConfig.v1",
        "api_base_url": None,
    }
    awaken = (SITE / "static/js/awaken.js").read_text(encoding="utf-8")
    assert "project?.compile_available && project?.public_compile_gateway" in awaken
    assert "selectedFiles.length !== 2" in awaken
    assert "runProductionFlow()" in awaken
    gateway = (SITE / "static/js/rss_vnext_api_gateway_v1.js").read_text(encoding="utf-8")
    assert "parsed.protocol !== 'https:'" in gateway
    assert "url.pathname.startsWith('/api/')" in gateway
    assert "nativeFetch(input, init)" in gateway


def test_two_observations_are_required_in_product_ui():
    html = (SITE / "index.html").read_text(encoding="utf-8")
    assert 'id="backSlotFile">REQUIRED<' in html
    assert "FRONT · BACK REQUIRED" in html
    js = (SITE / "static/js/awaken_input_slots.js").read_text(encoding="utf-8")
    assert "A matching back source view is required for RSS.vNext" in js
