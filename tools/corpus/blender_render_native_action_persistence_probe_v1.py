def require(ok, code):
    if not ok:
        raise RuntimeError(code)


def digest(a):
    return hashlib.sha256(np.asarray(a, np.float32).tobytes()).hexdigest()


def render_image(path):
    scene = bpy.context.scene
    scene.render.filepath = str(path)
    bpy.ops.render.render(write_still=True)
    image = bpy.data.images.load(str(path), check_existing=False)
    try:
        pixels = np.array(image.pixels[:], dtype=np.float32).reshape(-1, 4)
        require(pixels.shape == (96 * 96, 4), "PERSISTENCE_RGBA_RESOLUTION")
        require(np.isfinite(pixels).all(), "PERSISTENCE_RGBA_NONFINITE")
        return pixels
    finally:
        bpy.data.images.remove(image)


def image_changed(a, b):
    return int(np.count_nonzero(
        np.max(np.abs(a - b), axis=1) > (4. / 255.)
    ))


